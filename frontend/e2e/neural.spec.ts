test('conversa temporária não cria neurônios e exclusão remove apenas o alvo',async({page})=>{
  const document=await seed(page)
  await page.getByRole('button',{name:'Configurações neurais'}).click()
  const autosave=page.getByLabel('Salvar perguntas, respostas e pesquisas no cérebro')
  await page.route('**/api/neural/preferences',async route=>{
    if(route.request().method()==='PUT')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Falha de persistência de teste'})})
    else await route.continue()
  })
  await autosave.click()
  await expect(page.getByRole('alert')).toContainText('Falha de persistência de teste')
  await expect(autosave).toBeChecked()
  await page.unroute('**/api/neural/preferences')
  await page.getByRole('button',{name:'Iniciar conversa temporária'}).click()
  await page.getByRole('button',{name:'Fechar diálogo'}).click()
  const before=await page.request.get('/api/neural/graph').then(r=>r.json())
  await page.getByLabel('Perguntar ao cérebro').fill('Uma pergunta temporária que não será registrada')
  await page.getByRole('button',{name:'Enviar pergunta neural'}).click()
  await expect(page.locator('.neural-last-answer')).toContainText('não está configurado')
  const after=await page.request.get('/api/neural/graph').then(r=>r.json())
  expect(after.total).toBe(before.total)
  await page.getByTestId('memory-'+document.node_id).click()
  await page.getByRole('button',{name:'Excluir memória selecionada'}).click()
  await page.getByRole('button',{name:'Confirmar exclusão',exact:true}).click()
  await expect(page.getByTestId('memory-'+document.node_id)).not.toBeVisible()
  expect((await page.request.get('/api/documents')).status()).toBe(200)
})
test('PDF original é desenhado no visualizador real',async({page})=>{
  // PDF mínimo real com página, fonte e stream de texto; offsets calculados no teste.
  const objects=['<< /Type /Catalog /Pages 2 0 R >>','<< /Type /Pages /Kids [3 0 R] /Count 1 >>','<< /Type /Page /Parent 2 0 R /MediaBox [0 0 500 500] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>','<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>']
  const stream='BT /F1 14 Tf 50 400 Td (Memoria neural sobre Roma) Tj ET';objects.push(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`)
  let pdf='%PDF-1.4\n';const offsets=[0];for(let i=0;i<objects.length;i++){offsets.push(pdf.length);pdf+=`${i+1} 0 obj\n${objects[i]}\nendobj\n`}
  const start=pdf.length;pdf+='xref\n0 6\n0000000000 65535 f \n'+offsets.slice(1).map(n=>String(n).padStart(10,'0')+' 00000 n \n').join('')+`trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${start}\n%%EOF`
  const response=await page.request.post('/api/documents',{multipart:{file:{name:'TESTE-neural.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdf)}}})
  expect(response.status()).toBe(201);const document=await response.json()
  await page.getByTestId('memory-'+document.node_id).dblclick()
  await expect(page.locator('.pdf-controls')).toContainText('Página 1 de 1')
  await expect.poll(()=>page.locator('.pdf-reader canvas').evaluate((canvas:HTMLCanvasElement)=>canvas.width)).toBeGreaterThan(100)
  await expect(page.locator('.reader-error')).not.toBeVisible()
})
test('1.000 nós instanciados medem FPS e câmera continua controlável',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.setViewportSize({width:1536,height:1000})
  await page.getByRole('button',{name:'Configurações neurais'}).click()
  await page.getByLabel('Modo de desempenho').check()
  await page.getByLabel('Teste visual com 1.000 nós sintéticos').check()
  await page.getByRole('button',{name:'Fechar diálogo'}).click()
  await expect(page.getByTestId('neural-stage')).toHaveAttribute('data-memory-count','1000')
  await expect(page.locator('.synthetic-status')).toBeVisible()
  await expect.poll(async()=>parseInt(await page.getByLabel('FPS do cenário').innerText())).toBeGreaterThanOrEqual(15)
  const values:number[]=[]
  for(let i=0;i<4;i++){await page.waitForTimeout(1100);values.push(parseInt(await page.getByLabel('FPS do cenário').innerText()))}
  await writeFile('test-results/neural-performance.json',JSON.stringify({nodes:1000,mode:'desempenho',browser:'Chromium headless SwiftShader',viewport:'1536x1000',fps_samples:values,average:values.reduce((a,b)=>a+b,0)/values.length},null,2))
  await page.screenshot({path:'test-results/neural-1000.png',animations:'disabled'})
  await page.getByRole('button',{name:'Habilitar gestos neurais'}).click()
  await expect(page.getByRole('button',{name:'Pausar câmera neural'})).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'Pausar câmera neural'}).click()
  await expect(page.getByRole('button',{name:'Habilitar gestos neurais'})).toBeVisible()
  expect(errors).toEqual([])
  expect((await page.request.get('/api/neural/graph').then(r=>r.json())).total).toBe(0)
})
